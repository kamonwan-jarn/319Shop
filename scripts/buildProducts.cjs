const allCategories = {
  "electronics": electronicsTemplates,
  "jewelery": jeweleryTemplates,
  "men's clothing": mensTemplates,
  "women's clothing": womensTemplates
}

const products = []
let id = 21 // 21 to 520

for (const [category, templates] of Object.entries(allCategories)) {
  for (let i = 0; i < templates.length; i++) {
    const tmpl = templates[i]
    for (let j = 0; j < 5; j++) {
      const title = tmpl.names[j]
      const priceOffset = ((j * 3) % 7) - 3
      const price = Math.max(9.99, Number((tmpl.basePrice + priceOffset * 1.5).toFixed(2)))
      const rate = Number((4.1 + ((i * 7 + j * 3) % 9) * 0.1).toFixed(1))
      const count = 40 + ((i * 23 + j * 37) % 450)

      products.push({
        id: id++,
        title,
        price,
        description: tmpl.desc,
        category,
        image: tmpl.image,
        rating: {
          rate,
          count
        }
      })
    }
  }
}

console.log("Total generated products:", products.length)
console.log("ID range:", products[0].id, "to", products[products.length - 1].id)

// Verify uniqueness of titles
const titlesSet = new Set(products.map(p => p.title))
console.log("Unique titles count:", titlesSet.size, "/", products.length)
if (titlesSet.size !== products.length) {
  console.error("Duplicate titles found!")
}

// Check if any title contains "(รุ่นที่"
const hasVersionSuffix = products.some(p => p.title.includes("(รุ่นที่"))
console.log("Has placeholder suffixes:", hasVersionSuffix)

